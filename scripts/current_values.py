def _dig(obj, path):
    # path is a list of keys, or a dotted string (split on "."). A list is
    # required when a key CONTAINS a dot, e.g. benchmark's
    # "mrq.temporal_samples".
    cur = obj
    for k in (path if isinstance(path, list) else path.split(".")):
        cur = cur[k]
    return cur


