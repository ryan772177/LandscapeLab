def verify_rows(rows=None):
    """Return (ok, failures). Each JSON-backed row's live source value must
    match the needle that also appears in the printed in_force string."""
    recipe, bench = _load(RECIPE), _load(BENCH)
    src = {"recipe": recipe, "bench": bench}
    failures = []
    for value, in_force, _r, _rb, _b, verify in (rows if rows is not None
                                                 else _rows()):
        if verify is None:
            continue
        sf, path, xf, needle = verify
        try:
            live = xf(_dig(src[sf], path))
        except Exception as e:  # noqa
            failures.append("%s: source read failed (%s.%s): %s"
                            % (value, sf, path, e))
            continue
        if live != needle:
            failures.append("%s: source %s.%s = %r but table says %r"
                            % (value, sf, path, live, needle))
        elif needle.lower() not in in_force.lower():
            failures.append("%s: needle %r not in the in-force text %r"
                            % (value, needle, in_force))
    return (not failures), failures


def table_md():
    lines = [BEGIN,
             "# CURRENT VALUES -- the in-force spec, generated (do not hand-edit)",
             "",
             "**Generated by `scripts/current_values.py` from "
             "`recipes/alpine_8k.json` + `benchmark.json`. Selftest asserts "
             "every JSON-backed row equals its source; ruling-only rows carry "
             "no source and say so.** Regenerate with "
             "`python scripts/current_values.py --write`.",
             "",
             "⭐ **BASELINE RULE:** no capture before 2026-09-15 Block A is a "
             "baseline. The **A-6 certified capture** (card R/G 1.0014, B/G "
             "0.998) is the ZERO for every comparison from here; earlier "
             "frames predate the joint WB solve, the D6000 shade floor, "
             "R-SKYCOLOR and the uniform-4096 world.",
             "",
             "| value | in force | ruling | read-back | basis | source |",
             "|---|---|---|---|---|---|"]
    for value, in_force, ruling, rb, basis, verify in _rows():
        source = ("%s `%s`" % verify[:2][::-1]) if verify else "ruling (no JSON)"
        lines.append("| %s | %s | %s | %s | %s | %s |"
                     % (value, in_force, ruling, rb, basis, source))
    lines.append(END)
    return "\n".join(lines)


def write_into_recipes():
    path = os.path.join(REPO, "RECIPES.md")
    with open(path, encoding="utf-8") as fh:
        body = fh.read()
    block = table_md()
    if BEGIN in body and END in body:
        body = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block,
                      body, count=1, flags=re.DOTALL)
    else:
        # Insert as the FIRST section, right after the H1 title line.
        nl = body.index("\n")
        body = body[:nl + 1] + "\n" + block + "\n" + body[nl + 1:]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(body)
    return path


def selftest():
    ok, failures = verify_rows()
    n = sum(1 for r in _rows() if r[5] is not None)
    print("  %d JSON-backed rows checked against source" % n)
    for f in failures:
        print("  FAIL:", f)
    # FAIL DIRECTION: a source that disagrees with the table MUST be caught,
    # or the check is decorative. Corrupt one row's needle and confirm
    # verify_rows refuses.
    bad = list(_rows())
    v = bad[3][5]                            # compensation_ev's verify tuple
    bad[3] = bad[3][:5] + ((v[0], v[1], v[2], "-99.9"),)
    caught = not verify_rows(bad)[0]
    print("  fail-direction (wrong needle refused): %s" % ("PASS" if caught
                                                           else "FAIL"))
    ok = ok and caught
    print("selftest %s" % ("OK" if ok else "FAILED"))
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if a.write:
        ok, failures = verify_rows()
        if not ok:
            print("REFUSE: not writing -- rows disagree with source:")
            for f in failures:
                print("  ", f)
            return 1
        p = write_into_recipes()
        print("wrote CURRENT VALUES into", os.path.relpath(p, REPO))
        return 0
    print(table_md())
    return 0


